class Command(BaseCommand):
    help = ("Створює розділи/параграфи 6 класу за офіційною навчальною програмою МОН "
           "(Мерзляк та ін.), звіреною напряму з первинним документом.")

    @transaction.atomic
    def handle(self, *args, **options):
        subject, _ = Subject.objects.get_or_create(code="math", defaults={"name_uk": "Математика"})
        grade, _ = Grade.objects.get_or_create(subject=subject, number=6, defaults={"name_uk": "6 клас"})

        sha = hashlib.sha256(b"mon-ua-math-grade6-2024-verified").hexdigest()
        textbook, _ = Textbook.objects.get_or_create(
            pdf_sha256=sha,
            defaults=dict(
                subject=subject, grade=grade, profile_code="mon_grade6",
                title="Навчальна програма «Математика», 6 клас (МОН України)",
                author="МОН України, модельна програма Мерзляк А.Г. та ін.", year=2024,
            ),
        )
        Section.objects.filter(textbook=textbook).delete()

        for s_idx, section_data in enumerate(SECTIONS, start=1):
            section = Section.objects.create(
                grade=grade, textbook=textbook, number=s_idx, name_uk=section_data["name"]
            )
            for p_idx, name in enumerate(section_data["paragraphs"], start=1):
                Paragraph.objects.create(section=section, number=p_idx, name_uk=name)

        self.stdout.write(self.style.SUCCESS(
            f"Створено {len(SECTIONS)} розділи, "
            f"{sum(len(s['paragraphs']) for s in SECTIONS)} параграфів (6 клас, звірено з МОН)."
        ))
